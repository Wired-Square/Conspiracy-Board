//! Every file-type rule, stated once: the importers, the Inbox and the webview's
//! pickers and icons (through the generated `src/bindings/fileTypes.ts`) agree.
//!
//! The image and document sets are disjoint, and `.txt` is email: an mbox is often
//! exported or renamed as one, and the parser sniffs the bytes. Extensions route a
//! file; the parsers and extractors read what it really is.

pub const EMAIL_EXTENSIONS: &[&str] = &["eml", "mbox", "txt"];
pub const IMAGE_EXTENSIONS: &[&str] =
  &["jpg", "jpeg", "png", "gif", "webp", "heic", "heif", "tiff", "tif", "bmp", "avif", "svg"];
pub const DOCUMENT_EXTENSIONS: &[&str] = &["pdf", "doc", "docx", "xls", "xlsx", "ppt", "pptx"];
/// Not importable as cards of their own (they arrive as attachments), but iconned.
pub const VIDEO_EXTENSIONS: &[&str] = &["mp4", "m4v", "mov", "avi", "mkv", "webm", "wmv", "flv", "mpg", "mpeg", "3gp"];
pub const AUDIO_EXTENSIONS: &[&str] = &["mp3", "m4a", "aac", "wav", "aif", "aiff", "flac", "ogg", "oga", "opus", "wma"];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileKind {
  Email,
  Image,
  Document,
  Video,
  Audio,
}

/// The extension after the last dot, lowercased; none for `README` or `.hidden`.
fn extension(name: &str) -> Option<String> {
  name.rfind('.').filter(|&dot| dot > 0).map(|dot| name[dot + 1..].to_ascii_lowercase())
}

pub fn kind_of(name: &str) -> Option<FileKind> {
  let ext = extension(name)?;
  [
    (EMAIL_EXTENSIONS, FileKind::Email),
    (IMAGE_EXTENSIONS, FileKind::Image),
    (DOCUMENT_EXTENSIONS, FileKind::Document),
    (VIDEO_EXTENSIONS, FileKind::Video),
    (AUDIO_EXTENSIONS, FileKind::Audio),
  ]
  .into_iter()
  .find_map(|(exts, kind)| exts.contains(&ext.as_str()).then_some(kind))
}

/// What the Inbox takes: email, and the images and documents that become cards.
/// Anything else is left in the folder rather than mis-imported.
pub fn is_importable(name: &str) -> bool {
  matches!(kind_of(name), Some(FileKind::Email | FileKind::Image | FileKind::Document))
}

/// A document card's media type, from its extension; an image's never has to be named.
pub fn document_mime(name: &str) -> Option<&'static str> {
  Some(match extension(name)?.as_str() {
    "pdf" => "application/pdf",
    "doc" => "application/msword",
    "docx" => "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "xls" => "application/vnd.ms-excel",
    "xlsx" => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "ppt" => "application/vnd.ms-powerpoint",
    "pptx" => "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    _ => return None,
  })
}

pub fn file_name(path: &std::path::Path) -> String {
  path.file_name().map_or_else(|| path.display().to_string(), |n| n.to_string_lossy().into_owned())
}

/// An extension for storing a file under: the name's if it has one, else the media
/// type's subtype, else `bin`. `media_name` sanitises it further.
pub fn ext_of(name: Option<&str>, mime: Option<&str>) -> String {
  let from_mime = || Some(mime?.split('/').nth(1)?.split([';', '+']).next()?.to_string());
  name.and_then(extension).filter(|e| !e.is_empty()).or_else(from_mime).filter(|e| !e.is_empty()).unwrap_or_else(|| "bin".into())
}

/// The constants above as TypeScript, for `src/bindings/fileTypes.ts`.
#[cfg(test)]
pub fn typescript() -> String {
  let list = |name: &str, exts: &[&str]| format!("export const {name} = {} as const;\n", serde_json::json!(exts));
  [
    "// Generated from src-tauri/src/file_types.rs by `cargo test bindings`. Do not edit this file manually.\n"
      .to_string(),
    list("EMAIL_EXTENSIONS", EMAIL_EXTENSIONS),
    list("IMAGE_EXTENSIONS", IMAGE_EXTENSIONS),
    list("DOCUMENT_EXTENSIONS", DOCUMENT_EXTENSIONS),
    list("VIDEO_EXTENSIONS", VIDEO_EXTENSIONS),
    list("AUDIO_EXTENSIONS", AUDIO_EXTENSIONS),
  ]
  .concat()
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn images_match_common_photo_extensions_case_insensitively() {
    for n in ["a.jpg", "a.JPEG", "b.png", "c.heic", "d.tif", "e.tiff", "f.webp", "g.avif", "h.svg"] {
      assert_eq!(kind_of(n), Some(FileKind::Image), "{n}");
    }
    for n in ["a.pdf", "b.docx", "c.eml", "d.txt"] {
      assert_ne!(kind_of(n), Some(FileKind::Image), "{n}");
    }
  }

  #[test]
  fn documents_are_pdf_and_office_modern_and_legacy_but_never_txt() {
    for n in ["a.pdf", "b.doc", "b.docx", "c.xls", "c.xlsx", "d.ppt", "d.pptx", "E.PDF"] {
      assert_eq!(kind_of(n), Some(FileKind::Document), "{n}");
    }
    for n in ["note.txt", "photo.png", "msg.eml"] {
      assert_ne!(kind_of(n), Some(FileKind::Document), "{n}");
    }
  }

  #[test]
  fn txt_is_email_everywhere_the_inbox_included() {
    for n in ["thread.eml", "Archive.mbox", "export.TXT"] {
      assert_eq!(kind_of(n), Some(FileKind::Email), "{n}");
      assert!(is_importable(n), "{n}");
    }
  }

  #[test]
  fn the_inbox_takes_email_images_and_documents_and_leaves_the_rest() {
    for n in ["IMG_1234.PNG", "chat.jpeg", "brief.pdf", "Report.DOCX"] {
      assert!(is_importable(n), "{n}");
    }
    for n in ["notes.md", "readme", "clip.mov", "voice.m4a", ".eml"] {
      assert!(!is_importable(n), "{n}");
    }
    assert_eq!(kind_of("clip.MOV"), Some(FileKind::Video));
    assert_eq!(kind_of("voice.m4a"), Some(FileKind::Audio));
  }

  #[test]
  fn document_mime_maps_known_extensions_only() {
    assert_eq!(document_mime("a.pdf"), Some("application/pdf"));
    assert_eq!(document_mime("a.DOCX"), Some("application/vnd.openxmlformats-officedocument.wordprocessingml.document"));
    assert_eq!(document_mime("a.png"), None);
    assert_eq!(document_mime("noext"), None);
  }

  #[test]
  fn ext_of_prefers_the_name_then_the_media_type() {
    assert_eq!(ext_of(Some("photo.PNG"), Some("image/jpeg")), "png");
    assert_eq!(ext_of(Some("README"), Some("image/svg+xml")), "svg");
    assert_eq!(ext_of(None, Some("text/plain; charset=utf-8")), "plain");
    assert_eq!(ext_of(Some(".hidden"), None), "bin");
    assert_eq!(ext_of(None, None), "bin");
  }
}
